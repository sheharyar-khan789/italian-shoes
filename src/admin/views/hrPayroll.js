/**
 * Payroll: choose a month, generate (the server works out every payslip from the saved terms, attendance, leave, advances and sales), add one-off
 * bonuses or deductions, approve (posts to the accounts and locks the month), pay, and reverse or undo a payment. The browser sends only choices:
 * no amount typed here can change a calculated figure.
 */
import { esc } from "../../lib/format.js";
import { statCard, toast, confirmDialog, errorState, emptyState } from "../ui/kit.js";
import { money, formDialog, row, input, select, newKey } from "../ui/purchasing.js";
import { toPaisa } from "../ui/money.js";
import { labelTables } from "../financeUi.js";
import { adminTable, exportReport } from "../analyticsUi.js";
import { call, messageOf, statusTag, thisMonth, todayKey, methodOptions, payslipReport, printLocal } from "../hrUi.js";

export default async function hrPayroll({ main, user }) {
  const p = user.perms;
  const can = { generate: p.includes("hr.payroll.generate"), approve: p.includes("hr.payroll.approve"), pay: p.includes("hr.payroll.pay"), exp: p.includes("hr.export") };
  let month = thisMonth();
  main.innerHTML = `
    <div class="adm-page">
      <header class="adm-page__head"><h1 class="adm-h1">Pay<em>roll</em></h1><p class="muted">Net salary = basic + allowances + overtime + bonuses + commissions − deductions. Everything is calculated by the server; approving posts to your accounts and locks the month.</p></header>
      <div class="adm-filters"><div class="field"><label for="pr-month">Month</label><input id="pr-month" type="month" value="${month}" max="${thisMonth()}" /></div></div>
      <div data-out><p class="muted">Loading…</p></div>
    </div>`;
  const out = /** @type {HTMLElement} */ (main.querySelector("[data-out]"));
  const alive = () => main.isConnected && main.querySelector("[data-out]") !== null;
  main.querySelector("#pr-month").addEventListener("change", (e) => {
    month = /** @type {HTMLInputElement} */ (e.target).value || thisMonth();
    show();
  });

  async function show() {
    out.innerHTML = `<p class="muted">Loading…</p>`;
    try {
      const [r, adj] = await Promise.all([call("payrollRun", { month }), call("listPayrollAdjustments", { month }).then((x) => x.adjustments).catch(() => [])]);
      if (!alive()) return;
      const run = r.run;
      const status = run?.status ?? "none";
      const t = run?.totals;
      const unpaid = r.payslips.filter((s) => s.status === "approved");
      out.innerHTML = `
        ${r.accounts.enabled && r.accounts.missing.length ? `<p class="form-alert" role="alert">Payroll accounts are missing from your chart of accounts: ${esc(r.accounts.missing.map((m) => m.label).join(", "))}. <button type="button" class="btn btn--ghost" data-setup>Set up payroll accounts</button></p>` : ""}
        ${!r.accounts.enabled ? `<p class="notice" role="status">Accounting isn't set up, so payroll won't be posted to the accounts. Set up Accounting first to keep your books in line.</p>` : ""}
        <p>${status === "none" ? `<span class="tag tag--low">Not generated</span>` : statusTag(status)} ${run?.generatedByName ? `<span class="muted">generated by ${esc(run.generatedByName)}</span>` : ""} ${run?.journal?.number ? `<span class="muted">· journal ${esc(run.journal.number)}</span>` : ""}</p>
        ${t ? `<div class="adm-stats">${statCard({ label: "Employees", value: run.employees })}${statCard({ label: "Gross pay", value: money(t.gross) })}${statCard({ label: "Deductions", value: money(t.deductions), note: t.advanceDeduction ? `${money(t.advanceDeduction)} loans & advances` : "" })}${statCard({ label: "Net payable", value: money(t.net) })}${statCard({ label: "Paid", value: `${run.paidCount ?? 0} of ${run.employees}` })}</div>` : ""}
        ${run?.skipped?.length ? `<p class="form-alert" role="status">Left out because they have no basic salary: ${esc(run.skipped.map((s) => s.name).join(", "))}.</p>` : ""}
        <p>
          ${can.generate && ["none", "draft"].includes(status) ? `<button type="button" class="btn btn--primary" data-gen><span>${status === "none" ? "Generate payroll" : "Recalculate"}</span></button> <button type="button" class="btn btn--ghost" data-adj>Add bonus / deduction</button> ` : ""}
          ${can.approve && status === "draft" ? `<button type="button" class="btn btn--primary" data-approve><span>Approve payroll</span></button> ` : ""}
          ${can.approve && status === "approved" ? `<button type="button" class="btn btn--ghost" data-reverse>Reverse payroll</button> ` : ""}
          ${can.pay && unpaid.length ? `<button type="button" class="btn btn--primary" data-pay><span>Pay salaries</span></button>` : ""}
        </p>
        ${r.payslips.length ? `<div class="adm-table-wrap"><table class="adm-table"><thead><tr>${can.pay && status !== "draft" ? "<th></th>" : ""}<th>Employee</th><th>Gross</th><th>Deductions</th><th>Net</th><th>Status</th><th></th></tr></thead><tbody>${r.payslips.map((s) => `<tr>${can.pay && status !== "draft" ? `<td>${s.status === "approved" ? `<input type="checkbox" data-sel="${esc(s.employeeId)}" aria-label="Pay ${esc(s.name)}" checked />` : ""}</td>` : ""}<td data-label="Employee"><strong>${esc(s.name)}</strong><br /><span class="muted">${esc(s.employeeNo)}${s.designation ? ` · ${esc(s.designation)}` : ""}</span>${s.warnings?.length ? `<br /><span class="form-alert">${esc(s.warnings.join("; "))}</span>` : ""}</td><td data-label="Gross">${esc(money(s.gross))}</td><td data-label="Deductions">${esc(money(s.deductions))}</td><td data-label="Net"><strong>${esc(money(s.net))}</strong></td><td data-label="Status">${statusTag(s.status)}${s.paidOn ? `<br /><span class="muted">${esc(s.paidOn)}</span>` : ""}</td><td><button type="button" class="text-btn" data-slip="${esc(s.employeeId)}">Payslip</button></td></tr>`).join("")}</tbody></table></div>` : emptyState({ title: "No payroll for this month yet", text: can.generate ? "Press “Generate payroll” to calculate every payslip from the records." : "" })}
        ${adj.length ? `<h2 class="adm-h2">Bonuses, allowances and deductions entered for ${esc(month)}</h2><div class="adm-table-wrap"><table class="adm-table"><thead><tr><th>Employee</th><th>Kind</th><th>Name</th><th>Amount</th><th>Reason</th><th></th></tr></thead><tbody>${adj.map((a) => `<tr><td data-label="Employee">${esc(a.employeeName)}</td><td data-label="Kind">${esc(a.kind)}</td><td data-label="Name">${esc(a.name)}</td><td data-label="Amount">${esc(money(a.amount))}</td><td data-label="Reason">${esc(a.reason)}</td><td>${can.generate && ["none", "draft"].includes(status) ? `<button type="button" class="text-btn" data-rmadj="${esc(a.id)}">Remove</button>` : ""}</td></tr>`).join("")}</tbody></table></div>` : ""}`;
      labelTables(out);
      wire(r, run, status, unpaid);
    } catch (err) {
      if (alive()) {
        out.innerHTML = errorState(messageOf(err));
        out.querySelector("[data-retry]")?.addEventListener("click", show);
      }
    }
  }

  const act = async (fn, okText) => {
    try {
      await fn();
      if (okText) toast(okText);
    } catch (err) {
      toast(messageOf(err), "error");
    }
    show();
  };

  function wire(r, run, status, unpaid) {
    out.querySelector("[data-setup]")?.addEventListener("click", () => act(() => call("setupHrAccounts", {}), "Payroll accounts are ready."));
    out.querySelector("[data-gen]")?.addEventListener("click", (e) => {
      /** @type {HTMLButtonElement} */ (e.currentTarget).disabled = true;
      act(() => call("generatePayroll", { month }), "Payroll calculated.");
    });
    out.querySelector("[data-approve]")?.addEventListener("click", async () => {
      if (!(await confirmDialog({ title: `Approve payroll for ${month}?`, body: `Net payable ${money(run.totals.net)}. It is posted to your accounts, loan instalments are taken off, and the month's attendance and leave are locked.`, confirm: "Approve" }))) return;
      act(() => call("approvePayroll", { month }), "Payroll approved and posted.");
    });
    out.querySelector("[data-reverse]")?.addEventListener("click", () => formDialog({
      title: `Reverse payroll for ${month}`,
      intro: "Salaries must not have been paid. A reversal entry is posted to the accounts, loan instalments are given back and the month reopens.",
      body: row("reason", "Reason", input("reason", 'maxlength="200"')),
      submit: "Reverse",
      async onSubmit(form, { show: err, close }) {
        const reason = String(new FormData(form).get("reason") ?? "").trim();
        if (reason.length < 3) return err("Give a reason.", { reason: "Required" });
        await call("reversePayroll", { month, reason });
        close();
        toast("Payroll reversed.");
        show();
      },
    }));
    out.querySelector("[data-adj]")?.addEventListener("click", () => {
      formDialog({
        title: "Add a one-off bonus, allowance or deduction",
        intro: `For ${month} only. Commission isn't entered here: it is worked out from sales by the rules in HR settings.`,
        body: `${row("employeeId", "Employee", select("employeeId", r.payslips.map((s) => [s.employeeId, s.name])))}${row("kind", "Kind", select("kind", [["bonus", "Bonus"], ["allowance", "Allowance"], ["deduction", "Deduction"]], "bonus"))}${row("name", "Name (e.g. Eid bonus)", input("name", 'maxlength="60"'))}${row("amount", "Amount (Rs)", input("amount", 'inputmode="decimal"'))}${row("reason", "Reason", input("reason", 'maxlength="200"'))}`,
        async onSubmit(form, { show: err, close }) {
          const f = /** @type {any} */ (form.elements);
          const amount = toPaisa(f.amount.value);
          if (!amount || Number.isNaN(amount)) return err("Enter the amount in rupees.", { amount: "Required" });
          if (f.name.value.trim().length < 2) return err("Give it a name.", { name: "Required" });
          if (f.reason.value.trim().length < 3) return err("Give a reason.", { reason: "Required" });
          await call("addPayrollAdjustment", { month, employeeId: f.employeeId.value, kind: f.kind.value, name: f.name.value.trim(), amount, reason: f.reason.value.trim() });
          close();
          toast("Added. Press “Recalculate” to include it.");
          show();
        },
      });
    });
    out.querySelectorAll("[data-rmadj]").forEach((b) => b.addEventListener("click", () => act(() => call("deletePayrollAdjustment", { id: /** @type {HTMLElement} */ (b).dataset.rmadj }), "Removed. Press “Recalculate”.")));
    out.querySelector("[data-pay]")?.addEventListener("click", () => {
      const ids = [...out.querySelectorAll("[data-sel]:checked")].map((x) => /** @type {HTMLElement} */ (x).dataset.sel);
      if (!ids.length) return toast("Tick the people to pay.", "error");
      const key = newKey();
      formDialog({
        title: `Pay ${ids.length} salar${ids.length === 1 ? "y" : "ies"}`,
        intro: `Total ${money(unpaid.filter((s) => ids.includes(s.employeeId)).reduce((n, s) => n + s.net, 0))}. Each is paid the way it is set on the employee unless you choose one method for all.`,
        body: `${row("method", "Pay by", select("method", [["", "As set for each employee"], ...methodOptions], ""))}${row("date", "Payment date", input("date", `type="date" value="${todayKey()}" max="${todayKey()}"`))}${row("reference", "Transfer reference (for bank and wallet payments)", input("reference", 'maxlength="80"'))}`,
        submit: "Record payment",
        async onSubmit(form, { show: err, close }) {
          const f = /** @type {any} */ (form.elements);
          const res = await call("paySalaries", { idempotencyKey: key, month, employeeIds: ids.slice(0, 40), ...(f.method.value ? { method: f.method.value } : {}), date: f.date.value, reference: f.reference.value.trim() }).catch((e) => {
            err(messageOf(e));
            return null;
          });
          if (!res) return;
          close();
          toast(`${res.paid} paid${ids.length > 40 ? " (the first 40: press again for the rest)" : ""}.`);
          show();
        },
      });
    });
    out.querySelectorAll("[data-slip]").forEach((b) => b.addEventListener("click", () => slipDialog(/** @type {string} */ (/** @type {HTMLElement} */ (b).dataset.slip))));
  }

  async function slipDialog(employeeId) {
    try {
      const { payslip } = await call("getPayslip", { month, employeeId });
      const rep = payslipReport(payslip);
      const d = document.createElement("dialog");
      d.className = "adm-dialog adm-dialog--wide";
      d.setAttribute("aria-label", "Payslip");
      d.innerHTML = `<div>${rep.tables.map((t) => adminTable(t)).join("")}<p class="muted">${rep.notes.map(esc).join(" ")}</p><p>${can.exp ? `<button type="button" class="btn btn--ghost" data-x="csv">CSV</button> <button type="button" class="btn btn--ghost" data-x="excel">Excel</button> <button type="button" class="btn btn--ghost" data-x="print">Print / PDF</button> ` : `<button type="button" class="btn btn--ghost" data-local>Print</button> `}${can.pay && payslip.status === "paid" ? `<button type="button" class="btn btn--ghost" data-void>Undo payment</button> ` : ""}<button type="button" class="btn btn--primary" data-close>Close</button></p><p class="form-alert" role="alert" data-msg hidden></p></div>`;
      document.body.append(d);
      d.addEventListener("close", () => d.remove());
      d.querySelector("[data-close]")?.addEventListener("click", () => d.close());
      d.querySelectorAll("[data-x]").forEach((b) => b.addEventListener("click", async () => {
        const msg = await exportReport(rep, /** @type {any} */ (/** @type {HTMLElement} */ (b).dataset.x), "hrExport");
        const m = /** @type {HTMLElement} */ (d.querySelector("[data-msg]"));
        m.textContent = msg;
        m.hidden = !msg;
      }));
      d.querySelector("[data-local]")?.addEventListener("click", () => printLocal(rep));
      d.querySelector("[data-void]")?.addEventListener("click", () => {
        d.close();
        formDialog({
          title: `Undo the payment to ${payslip.name}`,
          intro: "A reversal entry is posted; the original entry stays.",
          body: row("reason", "Reason", input("reason", 'maxlength="200"')),
          submit: "Undo payment",
          async onSubmit(form, { show: err, close }) {
            const reason = String(new FormData(form).get("reason") ?? "").trim();
            if (reason.length < 3) return err("Give a reason.", { reason: "Required" });
            await call("voidSalaryPayment", { month, employeeId, reason });
            close();
            toast("Payment undone.");
            show();
          },
        });
      });
      d.showModal();
    } catch (err) {
      toast(messageOf(err), "error");
    }
  }
  await show();
}
